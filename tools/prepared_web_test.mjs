// Actual frontend script in a minimal DOM. Synthetic test; no YouTube/H728.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {webcrypto} from 'node:crypto';
const elements = new Map();
const element = () => ({value:'',textContent:'',hidden:false,disabled:false,dataset:{},children:[],
    setAttribute(k,v){this[k]=v}, removeAttribute(k){delete this[k]}, append(...items){this.children.push(...items)}, replaceChildren(){this.children=[]}, addEventListener(){}});
const ctx=vm.createContext({document:{getElementById(id){if(!elements.has(id))elements.set(id,element());return elements.get(id)},createElement:element,querySelectorAll:()=>[]},
    localStorage:{getItem:()=>null,setItem(){},removeItem(){}},crypto:webcrypto,setInterval(){},setTimeout(){},clearTimeout(){}});
vm.runInContext(fs.readFileSync('app/src/main/assets/web/app.js','utf8'),ctx);
vm.runInContext(`state={status:'LOADING',prepared:{enabled:true,paused:true,ready:1,count:2,entries:[
    {index:1,title:'<img src=x onerror=alert(1)>',status:'READY',bytes:1048576},
    {index:2,videoId:'video000002',status:'ERROR',bytes:0,error:'YOUTUBE_AUTH_REQUIRED'}]}};renderPrepared()`,ctx);
assert(elements.get('preparedSummary').textContent.includes('Готово в текущем плане: 1 из 2'));
assert(elements.get('preparedSummary').textContent.includes('остановлена'));
const rows=elements.get('preparedEntries').children;
assert(rows[0].children[0].textContent.includes('<img src=x onerror=alert(1)>'));
assert(!('innerHTML' in rows[0]),'Untrusted titles must remain text');
assert(rows[1].children[0].textContent.includes('YouTube требует авторизацию'));
assert.equal(rows[1].children[1].hidden,true,'Failed download must not look like active indeterminate progress');
assert(elements.get('playerStatus').textContent.includes('полностью подготовленного файла'));
const html=fs.readFileSync('app/src/main/assets/web/index.html','utf8');
for(const action of ['ENABLE','DISABLE','PAUSE','RETRY','CLEANUP','DELETE_ALL','RETRY_DELETE']) assert(html.includes(`data-prepared="${action}"`));
vm.runInContext(`state.queueVersion=42; state.prepared.limitBytes=10737418240; state.prepared.reserveBytes=1073741824;
 state.prepared.entries=[0,42,null,100].map((percent,index)=>({index:index+1,videoId:'video000001',status:index===3?'READY':'DOWNLOADING',phase:'AUDIO',percent,bytes:4194304,totalBytes:10000000}));renderPrepared()`,ctx);
const progressRows=elements.get('preparedEntries').children;
assert.equal(progressRows[0].children[1].value,0);
assert.equal(progressRows[1].children[1].value,42);
assert(!('value' in progressRows[2].children[1]),'Unknown size must remain indeterminate');
assert.equal(progressRows[2].children[1].hidden,false,'Active unknown-size download must retain its indicator');
assert.equal(progressRows[3].children[1].value,100);
assert(progressRows[1].children[0].textContent.includes('Загружаем звук; 42%'));
assert(elements.get('preparedStorage').textContent.includes('10.0 ГиБ'));
ctx.confirm=()=>false;
vm.runInContext(`var sent=[]; perform=async(key,path,payload)=>sent.push({path,payload});refreshState=async()=>{};`,ctx);
await vm.runInContext(`clearAllQueue()`,ctx);
await vm.runInContext(`preparationAction('DELETE_ALL')`,ctx);
await vm.runInContext(`preparationAction('DELETE','video000001')`,ctx);
assert.equal(vm.runInContext('sent.length',ctx),0,'Cancel must send no mutation');
ctx.confirm=()=>true;
await vm.runInContext(`clearAllQueue()`,ctx);
await vm.runInContext(`preparationAction('DELETE','video000001')`,ctx);
const sent=JSON.parse(vm.runInContext('JSON.stringify(sent)',ctx));
assert.equal(sent[0].path,'/api/queue/clear-all');
assert.equal(sent[0].payload.queueVersion,42);
assert.equal(sent[1].path,'/api/prepared');
assert.equal(sent[1].payload.videoId,'video000001');
assert.equal(sent[1].payload.stopPlayback,true);
assert.notEqual(sent[0].payload.idempotencyKey,sent[1].payload.idempotencyKey);
vm.runInContext(`state.prepared={enabled:true,paused:true,ready:20,count:61,usedBytes:10704993730,freeBytes:4734377984,limitBytes:10737418240,reserveBytes:1073741824,additionalBytes:32424510,entries:[{index:20,status:'ERROR',bytes:0,error:'NO_SPACE'}]};renderPrepared()`,ctx);
assert.equal(elements.get('preparationAlert').hidden,false,'Storage block must be visible even when downloads are folded');
assert(elements.get('preparationAlert').textContent.includes('не хватает места в лимите 10.0 ГиБ'));
assert(elements.get('preparationAlert').textContent.includes('Выберите другое хранилище'));
assert(elements.get('preparedStorage').textContent.includes('30.9 МиБ'),'Small remaining allowance must not round to zero GiB');
vm.runInContext(`state.prepared.freeBytes=1073741824;renderPrepared()`,ctx);
assert(elements.get('preparationAlert').textContent.includes('с учётом резерва Android'));
vm.runInContext(`state.prepared.entries[0].error='NETWORK_RETRY';renderPrepared()`,ctx);
assert.equal(elements.get('preparationAlert').hidden,true,'A network retry is not a storage block');
vm.runInContext(`state.prepared.entries[0].error='NO_SPACE';state.prepared.paused=false;renderPrepared()`,ctx);
assert.equal(elements.get('preparationAlert').hidden,true,'An earlier error must not label a running preparation as stopped');
console.log('PASS: safe titles, readiness/auth, exact/unknown progress, quota, clear/delete confirmation and versioned commands (synthetic)');
